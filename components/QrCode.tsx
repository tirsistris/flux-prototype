// One path of 1×1 squares, merged per run of dark modules in a row.
const PATH = MATRIX.map((row, y) => {
  let d = "";
  row.replace(/1+/g, (run, x: number) => {
    d += `M${x} ${y}h${run.length}v1h-${run.length}z`;
    return run;
  });
  return d;
}).join("");

export function QrCode({ label }: { label: string }) {
  return (
    <div className="qr-plate" role="img" aria-label={label}>
      <svg className="qr-code" viewBox="0 0 41 41" shapeRendering="crispEdges" aria-hidden="true">
        <path d={PATH} fill="#141414" />
      </svg>
      <span className="qr-logo">
        <Coin asset="BTC" size={44} />
      </span>
    </div>
  );
}
